    public void listarJogosDoArbitroLogado(DefaultTableModel modeloTabela, UsuarioLogado sessaoAtual) throws Exception{
        modeloTabela.setRowCount(0);
        
        Usuario usuario = sessaoAtual.getUsuario();
           
        String nomeArbitroLogado = usuario.getNome();
        
        try{
            List<PartidaCopa> todasAsPartidas = new ArrayList<>();
            todasAsPartidas.addAll(new FaseGrupos().listarPartidas());
            todasAsPartidas.addAll(new OitavasFinal().listarPartidas());
            todasAsPartidas.addAll(new QuartasFinal().listarPartidas());
            todasAsPartidas.addAll(new SemiFinal().listarPartidas());
            todasAsPartidas.addAll(new Final().listarPartidas());
            
            for(PartidaCopa partida : todasAsPartidas){
                String arbitroDaPartida = partida.getArbitro();
                
                if(arbitroDaPartida != null && arbitroDaPartida.contains(nomeArbitroLogado)){
                    String fase = partida.getFase();
                    String confronto = partida.getSelecao1() + " x " + partida.getSelecao2();
                    String data = partida.getData();
                    String estadio = partida.getEstadio();
                    modeloTabela.addRow(new Object[]{fase, confronto, data, estadio});
                }
            }
        } catch(Exception e){
            System.err.println("Erro ao carregar os jogos " + e.getMessage());
        }
        
        
    }

